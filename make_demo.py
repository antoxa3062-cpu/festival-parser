# -*- coding: utf-8 -*-
"""Демо-отчёт с вымышленными данными (для скриншотов и портфолио).
Запуск: python make_demo.py  →  demo_report.html
"""
from datetime import datetime, timedelta
import parse_answers as pa

pa.CURATOR = "Куратор Демо"   # нейтральное имя только для демо
now = datetime.now()

def ago(hours):
    return "Время обновления ответа " + (now - timedelta(hours=hours)).strftime("%Y-%m-%d %H:%M:%S")

def row(name, lesson, hours, kind, text, reply):
    return {
        "урок_id": 1, "урок": lesson, "участник": name, "id участника": "0",
        "маркер (title)": "[DEMO] Куратор Демо", "статус": "Задание принято",
        "дата ответа": ago(hours), "ссылка на ответ": "https://example.com/answer",
        "комментарий куратора": reply,
        "ждёт ответа на комментарий": "да" if kind else "нет",
        "тип комментария": kind, "текст комментария": text,
        "время комментария": ago(hours), "почему ждёт": "",
    }

rows = [
    row("Участница А", "Урок 1. Практики", 30, "", "", "нет"),
    row("Участница Б", "Урок 1. Практики", 15, "", "", "нет"),
    row("Участница В", "Урок 2. Намерение", 3, "", "", "нет"),
    row("Участница Г", "Урок 2. Намерение", 5, "вопрос",
        "Подскажите, пожалуйста, как правильно сформулировать намерение?", "Куратор Демо"),
    row("Участница Д", "Урок 1. Практики", 8, "комментарий",
        "Сделала практику, поделюсь ощущениями позже.", "Куратор Демо"),
    row("Участница Е", "Урок 1. Практики", 2, "благодарность",
        "Благодарю за поддержку! 🙏", "Куратор Демо"),
]

pa.generate_html(rows, "demo_report.html")
print("Готово: demo_report.html (вымышленные данные)")

